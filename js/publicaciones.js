// FUNCIONAMIENTO DE LA SECCIÓN
// =========================
(() => {

    const list = document.getElementById("publicationsList");
    const search = document.getElementById("publicationSearch");
    const empty = document.getElementById("publicationsEmpty");

    const tabs = [
        ...document.querySelectorAll(".publications__tab")
    ];

    if (!list || !search || !empty || !tabs.length) {
        return;
    }

    // Por defecto busca entre publicaciones
    let currentFilter = "article";

    const profileUrl =
        "https://www.researchgate.net/profile/Ernesto-Brugnoli";


    // Evita problemas con caracteres especiales
    const escapeHtml = (value) => String(value)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");


    function render() {

        const term = search.value
            .trim()
            .toLocaleLowerCase("es");


        // =========================
        // SI NO ESCRIBE NADA
        // NO MOSTRAMOS PUBLICACIONES
        // =========================

        if (term === "") {

            list.innerHTML = `
                <div class="publications__search-message">
                    <span class="publications__search-message-icon">⌕</span>

                    <h3>Buscá una publicación</h3>

                    <p>
                        Escribí el título o alguna palabra relacionada
                        para encontrar trabajos de Ernesto Brugnoli.
                    </p>
                </div>
            `;

            empty.hidden = true;

            return;
        }


        // =========================
        // BUSCAR
        // =========================

        const filtered = publicationData.filter(item =>

            item.type === currentFilter &&

            (
                item.title
                    .toLocaleLowerCase("es")
                    .includes(term)

                ||

                item.year
                    .toLocaleLowerCase("es")
                    .includes(term)
            )

        );


        // =========================
        // MOSTRAR RESULTADOS
        // =========================

        list.innerHTML = filtered.map(item => `

            <article class="publication-card">

                <div class="publication-card__year">
                    ${escapeHtml(item.year)}
                </div>

                <div class="publication-card__content">

                    <p class="publication-card__type">
                        ${
                            item.type === "chapter"
                                ? "Capítulo de libro"
                                : "Publicación científica"
                        }
                    </p>

                    <h3 class="publication-card__title">
                        ${escapeHtml(item.title)}
                    </h3>

                </div>

                <a
                    class="publication-card__link"
                    href="${profileUrl}"
                    target="_blank"
                    rel="noopener noreferrer"
                    aria-label="Abrir ResearchGate"
                    title="Ver en ResearchGate"
                >
                    ↗
                </a>

            </article>

        `).join("");


        // Si no encuentra resultados
        empty.hidden = filtered.length !== 0;

    }


    // =========================
    // CAMBIAR CATEGORÍA
    // =========================

    tabs.forEach(tab => {

        tab.addEventListener("click", () => {

            currentFilter = tab.dataset.filter;

            tabs.forEach(btn => {

                btn.classList.toggle(
                    "publications__tab--active",
                    btn === tab
                );

            });

            // Limpiamos búsqueda al cambiar categoría
            search.value = "";

            render();

        });

    });


    // =========================
    // BUSCADOR EN TIEMPO REAL
    // =========================

    search.addEventListener("input", render);


    // Primera carga
    render();

})();